import fs from "node:fs";
import vm from "node:vm";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

export function buildEvidenceNarration() {
  const source = fs.readFileSync(new URL("../public/app.js", import.meta.url), "utf8");
  const start = source.indexOf("const demoCase = {");
  const end = source.indexOf("const caseChineseTranslations = {", start);
  if (start < 0 || end < 0) throw new Error("Built-in cases not found");
  const { caseLibrary, caseTranslations } = vm.runInNewContext(`${source.slice(start, end)}\n({ caseLibrary, caseTranslations })`, Object.create(null), { timeout: 1000 });
  const catalog = {};
  for (const id of ["moon-trial", "old-port-letter", "orbit-7", "velvet-room"]) {
    catalog[id] = {};
    for (const locale of ["zh", "en"]) {
      const base = caseLibrary[id];
      const translated = locale === "en" ? caseTranslations[id] : {};
      catalog[id][locale] = Object.fromEntries(base.evidence.map((original) => {
        const item = { ...original, ...translated?.evidence?.find((entry) => entry.id === original.id) };
        // Narrate only this opened clue, never other clues or the solution.
        const text = `${item.name}。${item.type}。${item.detail}`.replaceAll("。", locale === "en" ? ". " : "。");
        const hash = createHash("sha256").update(text).digest("hex").slice(0, 12);
        return [item.id, { text, sceneKey: `clue:${item.id}:${hash}`, audioUrl: `assets/narration/${id}/${locale}-clue-${item.id}-${hash}.mp3` }];
      }));
    }
  }
  return catalog;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = buildEvidenceNarration();
  const target = new URL("../public/evidence-narration.js", import.meta.url);
  const output = `// Generated by scripts/build-evidence-narration.mjs.\nwindow.NOCTURNE_EVIDENCE_NARRATION = ${JSON.stringify(catalog, null, 2)};\n`;
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output) throw new Error("Evidence narration manifest is out of date");
    let count = 0;
    for (const locales of Object.values(catalog)) for (const clues of Object.values(locales)) for (const clip of Object.values(clues)) {
      const file = new URL(`../public/${clip.audioUrl}`, import.meta.url);
      if (!fs.existsSync(file) || fs.statSync(file).size < 1000) throw new Error(`Missing clue audio: ${clip.audioUrl}`);
      count++;
    }
    console.log(`${count} bilingual clue recordings verified.`);
  } else fs.writeFileSync(target, output);
}
